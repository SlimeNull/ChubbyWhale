"""Build a skin's runtime sprites from its generated raw art.

Usage (from repo root):  python art/build_sprites.py [skin id]     (default: standard)
Requires Pillow. Reads <art dir>/raw/*.png (see SKINS at the bottom), writes
skins/<id>/sprites/*.webp + manifest.json.
"""

