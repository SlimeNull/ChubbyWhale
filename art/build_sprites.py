"""Build runtime sprites for Chubby Whale from the generated raw art.

Usage (from repo root):  python art/build_sprites.py
Requires Pillow. Reads art/raw/*.png, writes public/sprites/*.webp + manifest.json.
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageChops, ImageDraw, ImageFilter

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "art" / "raw"
OUT = ROOT / "public" / "sprites"

# Raw art comes back from the image API at varying sizes (e.g. 1216x1294); runtime sprites are
# downscaled by this factor (≈2x the default on-screen size, crisp on HiDPI).
SCALE = 0.42

# Per-pose tweaks after eyeballing the raw art:
#   scale:     extra multiplier so the head size matches the master
#   flip:      mirror horizontally so "look" faces the same way as the code assumes
#   crop_like: crop with another pose's box and use its anchor (frames of one
#              animation, or the peek family whose right edge must stay on the screen edge)
#   grip:      peek art — find the straight vertical cut where her body meets the
#              (invisible) wall and make it the sprite's right edge; anything past it
#              (an ear, a bow) is behind the wall. crop_like variants are shifted so
#              their cut lines match the base's.
POSES: dict[str, dict] = {
    "idle": {"src": "master.png"},
    "look": {},
    "yawn": {},
    "sleep": {"scale": 0.8},
    "dragged": {"scale": 0.9},
    "fly": {},
    "hurt": {"scale": 0.8},
    "happy": {"scale": 0.96},
    "cheer": {},
    "curious": {},
    "shocked": {},
    "watch": {"scale": 0.8},
    "shy": {},
    # Reaction variants
    "giggle": {},
    "pout": {},
    "proud": {},
    "dragged_happy": {"scale": 0.9},
    "dragged_grumpy": {"scale": 0.9},
    "dragged_limp": {"scale": 0.9},
    "fly_happy": {"scale": 0.85},
    "fly_ball": {"scale": 0.85},
    "hurt_cry": {"scale": 0.8},
    "hurt_dizzy": {"scale": 0.8},
    # Walk / run cycles (frames share one scale so the head doesn't pulse)
    "walk_a": {"scale": 0.97},
    "walk_pass": {"scale": 0.97},
    "walk_b": {"scale": 0.97},
    "run_a": {"scale": 0.97},
    "run_b": {"scale": 0.97},
    # Peeking from behind the right image edge (the screen edge when docked)
    "peek": {"scale": 0.9, "grip": True},
    "peek_wave": {"scale": 0.9, "crop_like": "peek"},
    "peek_smile": {"scale": 0.9, "crop_like": "peek"},
    "peek_sleepy": {"scale": 0.9, "crop_like": "peek"},
    # Everyday activities
    "eat": {"scale": 1.0},
    "eat_b": {"scale": 1.0, "crop_like": "eat"},
    "game": {"scale": 0.9},
    "game_b": {"scale": 0.9, "crop_like": "game"},
    "read": {"scale": 0.88},
    "tea": {"scale": 0.93},
    "music": {"scale": 0.93},
    "phone": {"scale": 0.8},
    "draw": {"scale": 0.92},
}

# Face patches generated by masked edits of the master (same canvas).
EYE_ELLIPSES = [(392, 402, 538, 552), (588, 388, 738, 540)]
MOUTH_ELLIPSES = [(512, 500, 612, 568)]
# Idle variants: (name, raw file, patched region). They share the idle crop.
IDLE_VARIANTS = [
    ("idle_blink", "blink.png", EYE_ELLIPSES),
    ("idle_talk", "talk.png", MOUTH_ELLIPSES),
]
# Gaze variants: which raw/gaze/ candidate each eye comes from, chosen by eye at
# real display size (equal pupil shifts are NOT the goal — the model moves each
# eye to suit its socket, so one image's two eyes usually belong together).
# Looking straight down came out cross-eyed in every both-eye edit (the lower lids
# slope toward the nose), so "d" combines two single-eye edits that also drift
# slightly outward.
GAZE_PICKS = {
    "l": ("l-0", "l-0"),
    "r": ("r-2", "r-0"),
    "u": ("u-0", "u-0"),
    "d": ("eye_left_d-3", "eye_right_d-3"),
    "ul": ("ul-0", "ul-0"),
    "ur": ("ur-1", "ur-1"),
}


def pupil(im: Image.Image, ellipse) -> tuple[float, float] | None:
    """Centroid of the dark iris/pupil pixels inside one eye (for the build report)."""
    x0, y0, x1, y1 = ellipse
    a = np.array(im.convert("RGB").crop(ellipse)).astype(int)
    R, G, B = a[..., 0], a[..., 1], a[..., 2]
    ys, xs = np.nonzero((B > R + 50) & (B > G + 20) & (R + G + B < 330))
    return (x0 + xs.mean(), y0 + ys.mean()) if len(xs) > 200 else None


def clean_alpha(im: Image.Image) -> Image.Image:
    """Drop the faint halo the generator leaves and make the body fully opaque."""
    im = im.convert("RGBA")
    a = im.getchannel("A").point(
        lambda v: 0 if v <= 16 else 255 if v >= 232 else int((v - 16) * 255 / 216)
    )
    im.putalpha(a)
    return im


def feather_mask(size, ellipses, grow=6, blur=7) -> Image.Image:
    m = Image.new("L", size, 0)
    d = ImageDraw.Draw(m)
    for x0, y0, x1, y1 in ellipses:
        d.ellipse((x0 + grow, y0 + grow, x1 - grow, y1 - grow), fill=255)
    return m.filter(ImageFilter.GaussianBlur(blur))


def patch(base: Image.Image, edited: Image.Image, ellipses) -> Image.Image:
    if edited.size != base.size:
        # The gateway sometimes returns the edit a pixel taller; align top-left.
        canvas = Image.new("RGBA", base.size)
        canvas.paste(edited, (0, 0))
        edited = canvas
    out = base.copy()
    out.paste(edited, (0, 0), feather_mask(base.size, ellipses))
    return out


def cut_line(im: Image.Image) -> int:
    """x of the straight vertical cut on the right side of peek art.

    The median of the right silhouette over the body rows (45%–85% of the
    height): the ear and hair stick out further up, the hands only a little.
    """
    a = np.array(im.getchannel("A")) > 200
    rows = np.where(a.any(axis=1))[0]
    top, bottom = rows.min(), rows.max()
    xs = [np.where(a[y])[0].max() for y in range(int(top + 0.45 * (bottom - top)), int(top + 0.85 * (bottom - top))) if a[y].any()]
    return int(np.median(xs))


def head_center_x(im: Image.Image) -> float:
    """Horizontal center of mass of the top 30% (the head), as a 0..1 fraction.

    The tail sticks out to one side, so the bbox center is not the body center.
    """
    a = im.getchannel("A")
    rows = max(1, int(a.height * 0.3))
    total = weighted = 0
    for y in range(0, rows, 2):
        for x in range(0, a.width, 2):
            v = a.getpixel((x, y))
            total += v
            weighted += v * x
    return round(weighted / total / a.width, 4) if total else 0.5


def export(name: str, im: Image.Image, crop_box, manifest: dict, extra_scale=1.0, flip=False):
    im = im.crop(crop_box)
    if flip:
        im = im.transpose(Image.Transpose.FLIP_LEFT_RIGHT)
    s = SCALE * extra_scale
    im = im.resize((max(1, round(im.width * s)), max(1, round(im.height * s))), Image.Resampling.LANCZOS)
    im.save(OUT / f"{name}.webp", quality=92, method=6, exact=True)
    manifest[name] = {"w": im.width, "h": im.height, "ax": head_center_x(im)}


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in [*OUT.glob("*.png"), *OUT.glob("*.webp")]:
        old.unlink()
    manifest: dict = {"scale": SCALE, "poses": {}, "variants": {}}

    for name, cfg in POSES.items():
        src = RAW / cfg.get("src", f"{name}.png")
        if not src.exists():
            print(f"skip {name}: {src.name} missing")
            continue
        im = clean_alpha(Image.open(src))
        bbox = im.getchannel("A").getbbox()
        base_cfg = POSES.get(cfg.get("crop_like", ""), {})
        if "crop_like" in cfg:
            other = clean_alpha(Image.open(RAW / base_cfg.get("src", f"{cfg['crop_like']}.png")))
            bbox = other.getchannel("A").getbbox()
            if base_cfg.get("grip"):
                # Line this variant's cut up with the base's, then cut there too.
                cut = cut_line(other)
                im = ImageChops.offset(im, cut - cut_line(im), 0)
                bbox = (bbox[0], bbox[1], cut + 1, bbox[3])
        if cfg.get("grip"):
            bbox = (bbox[0], bbox[1], cut_line(im) + 1, bbox[3])
        export(name, im, bbox, manifest["poses"], cfg.get("scale", 1.0), cfg.get("flip", False))
        if "crop_like" in cfg:
            # Same anchor as the base pose too, so the frames overlay exactly (no sideways jitter).
            manifest["poses"][name]["ax"] = manifest["poses"][cfg["crop_like"]]["ax"]

        if name == "idle":
            # Blink / talk / gaze variants share the idle crop so they swap without jitter.
            for vname, raw, ell in IDLE_VARIANTS:
                if (RAW / raw).exists():
                    v = patch(im, clean_alpha(Image.open(RAW / raw)), ell)
                    export(vname, v, bbox, manifest["variants"])
            # Gaze: left / right eye patched in from the picked candidates.
            base = [pupil(im, e) for e in EYE_ELLIPSES]
            for d, (lf, rf) in GAZE_PICKS.items():
                left, right = (clean_alpha(Image.open(RAW / "gaze" / f"{f}.png")) for f in (lf, rf))
                v = patch(patch(im, left, EYE_ELLIPSES[:1]), right, EYE_ELLIPSES[1:])
                export(f"idle_gaze_{d}", v, bbox, manifest["variants"])
                shifts = [np.round(np.subtract(pupil(v, e), b), 1).tolist() for e, b in zip(EYE_ELLIPSES, base)]
                print(f"idle_gaze_{d}: {lf} + {rf}, pupil shifts L {shifts[0]} R {shifts[1]}")

    (OUT / "manifest.json").write_text(json.dumps(manifest, indent=2))
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
